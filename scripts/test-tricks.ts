import assert from 'node:assert/strict';
import { evaluateLanding, Combo, grabName } from '../game/tricks';
const P = Math.PI;
let r = evaluateLanding({ spin: 2 * P + 0.1, flip: 0, grabTime: 0.5, grabKind: 'Japan', air: 1.4 });
assert.equal(r.name, '360 Japan');
assert.equal(r.quality, 'Perfect');
assert.ok(!r.switchFlip && r.speedFactor > 1);
r = evaluateLanding({ spin: 3 * P, flip: -2 * P, grabTime: 0, grabKind: null, air: 1.8 });
assert.equal(r.name, 'Backflip 540');
assert.ok(r.switchFlip, '540 = réception switch');
r = evaluateLanding({ spin: 0, flip: 4 * P + 0.5, grabTime: 0, grabKind: null, air: 2 });
assert.equal(r.name, 'Double frontflip');
assert.equal(r.quality, 'Good');
r = evaluateLanding({ spin: 0, flip: P, grabTime: 0, grabKind: null, air: 1 });
assert.ok(r.crash);
r = evaluateLanding({ spin: 2 * P + 0.6, flip: 0, grabTime: 0, grabKind: null, air: 1 });
assert.equal(r.quality, 'Good');
r = evaluateLanding({ spin: 0, flip: 0, grabTime: 0, grabKind: null, air: 0.4 });
assert.equal(r.name, null);
assert.equal(grabName(true, 0), 'Japan');
assert.equal(grabName(false, -1), 'Tail grab');

const c = new Combo();
c.add('360', 400);
c.add('Backflip', 800);
assert.equal(c.multiplier, 1.5);
assert.equal(c.total, 1800);
assert.equal(c.update(1, false), null, 'pas d’encaissement en l’air');
assert.equal(c.update(1, true), null);
assert.equal(c.update(2, true), 1800, 'encaissé après la fenêtre');
assert.ok(!c.active);
c.add('Grind', 100);
assert.equal(c.fail(), 100);
console.log('✓ figures & combos OK');
